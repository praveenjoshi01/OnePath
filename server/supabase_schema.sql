-- Supabase Schema DDL for OnePath Enrollment Manager

-- 1. Crèche Rooms Table
CREATE TABLE IF NOT EXISTS public.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    min_age_months INT NOT NULL,
    max_age_months INT NOT NULL,
    capacity INT NOT NULL,
    staff_ratio TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Applications (Prospective Children) Table
CREATE TABLE IF NOT EXISTS public.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    child_first_name TEXT NOT NULL,
    child_last_name TEXT NOT NULL,
    date_of_birth DATE NOT NULL,
    requested_start_date DATE NOT NULL,
    parent_name TEXT NOT NULL,
    parent_email TEXT NOT NULL,
    parent_phone TEXT DEFAULT '',
    enquiry_source TEXT DEFAULT 'Website',
    stage TEXT DEFAULT 'interest_captured',
    room_id BIGINT REFERENCES public.rooms(id) ON DELETE SET NULL,
    days_requested TEXT DEFAULT 'Full-time (5 Days)',
    sibling_priority BOOLEAN DEFAULT FALSE,
    deposit_paid BOOLEAN DEFAULT FALSE,
    deposit_amount NUMERIC DEFAULT 0.00,
    medical_notes TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    last_contact_date TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Follow-Up Tasks Table
CREATE TABLE IF NOT EXISTS public.tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    task_type TEXT NOT NULL,
    title TEXT NOT NULL,
    due_date DATE NOT NULL,
    status TEXT DEFAULT 'pending',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Sync Audit Logs Table
CREATE TABLE IF NOT EXISTS public.sync_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    target_platform TEXT NOT NULL,
    status TEXT NOT NULL,
    payload JSONB,
    response_message TEXT,
    synced_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) & Allow Public Read/Write for Demo
ALTER TABLE public.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.applications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sync_logs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read/write access to rooms" ON public.rooms FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write access to applications" ON public.applications FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write access to tasks" ON public.tasks FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow public read/write access to sync_logs" ON public.sync_logs FOR ALL USING (true) WITH CHECK (true);

